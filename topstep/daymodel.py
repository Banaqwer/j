"""Exact distribution of one trading day's P&L for a stopped trade walk.

The trader takes up to `n_steps` i.i.d. binary trades of size k (per-trade
P&L +k(R-c) or -k(L+c)) and stops the session as soon as the running P&L
reaches >= +delta (target) or <= -lam (stop); if neither happens the day ends
at the running P&L.  The distribution is computed exactly on the integer-cent
lattice generated by the two step sizes, then rounded to the DP grid h.
This captures overshoot (the real cost of a stop with asymmetric steps) and
unresolved sessions, which a binary +delta/-lam model cannot.
"""
from __future__ import annotations

import math
from dataclasses import dataclass

import numpy as np

from .edge import Edge

RESOLVE_PROB_MIN = 0.90      # preferred: the bet resolves within the session w.p. >= this
PROB_FLOOR = 1e-5            # outcomes with smaller probability are dropped (mass renormalised)


@dataclass(frozen=True)
class DayOutcomes:
    steps: np.ndarray        # P&L in grid units (int)
    prob: np.ndarray         # probabilities (sum to 1)
    p_win: float             # P(day ended at or above +delta)
    p_lose: float            # P(day ended at or below -lam)
    p_unresolved: float
    mean: float              # expected day P&L in $ (before grid rounding)
    k: int


def lattice_day_distribution(delta: float, lam: float, p_win: float, up: float, down: float, n_steps: int):
    """Returns (values_dollars, probs, p_win_abs, p_lose_abs, p_unresolved)."""
    u, d = int(round(up * 100)), int(round(down * 100))
    if u <= 0 or d <= 0:
        raise ValueError("step sizes must be positive")
    g = math.gcd(u, d)
    u, d = u // g, d // g
    a = int(math.ceil(delta * 100 / g - 1e-9))      # absorbed (win) at x >= a
    b = int(math.ceil(lam * 100 / g - 1e-9))        # absorbed (lose) at x <= -b
    a, b = max(a, 1), max(b, 1)
    lo = -(b - 1) - d
    hi = (a - 1) + u
    size = hi - lo + 1
    pos = np.arange(lo, hi + 1)
    mass = np.zeros(size)
    mass[-lo] = 1.0
    absorbed = np.zeros(size)
    t0, t1 = (-(b - 1)) - lo, (a - 1) - lo           # transient index range inclusive
    win_mask = pos >= a
    lose_mask = pos <= -b
    for _ in range(int(n_steps)):
        t = mass[t0:t1 + 1]
        if t.sum() < 1e-15:
            break
        new = np.zeros(size)
        new[t0 + u:t1 + u + 1] += p_win * t
        new[t0 - d:t1 - d + 1] += (1.0 - p_win) * t
        absorbed[win_mask] += new[win_mask]
        absorbed[lose_mask] += new[lose_mask]
        new[win_mask] = 0.0
        new[lose_mask] = 0.0
        mass = new
    p_w = float(absorbed[win_mask].sum())
    p_l = float(absorbed[lose_mask].sum())
    p_u = float(mass.sum())
    total = absorbed + mass
    keep = total > 0
    values = pos[keep] * g / 100.0
    return values, total[keep], p_w, p_l, p_u


def day_outcomes(delta: float, lam: float, k: int, edge: Edge, h: float) -> DayOutcomes:
    up = k * (edge.reward - edge.cost_rt)
    down = k * (edge.loss + edge.cost_rt)
    values, probs, pw, pl, pu = lattice_day_distribution(delta, lam, edge.p_win, up, down, edge.trades_per_day)
    mean = float((values * probs).sum())
    # mean-preserving ("stochastic") rounding: an off-grid value v splits its
    # probability between floor(v/h) and floor(v/h)+1 so that E[P&L] is exact.
    # Nearest-point rounding would refund the commission on every trade
    # (+95 -> +100, -105 -> -100) and let the DP farm a phantom edge.
    agg = {}
    for v, p_ in zip(values, probs):
        x = v / h
        lo = int(np.floor(x + 1e-12))
        frac = x - lo
        if frac < 1e-12:
            agg[lo] = agg.get(lo, 0.0) + float(p_)
        else:
            agg[lo] = agg.get(lo, 0.0) + float(p_) * (1.0 - frac)
            agg[lo + 1] = agg.get(lo + 1, 0.0) + float(p_) * frac
    items = [(s_, p_) for s_, p_ in agg.items() if p_ >= PROB_FLOOR]
    tot = sum(p_ for _, p_ in items)
    st = np.array([s_ for s_, _ in items], dtype=int)
    pr = np.array([p_ / tot for _, p_ in items])
    order = np.argsort(st)
    return DayOutcomes(st[order], pr[order], pw, pl, pu, mean, k)


def choose_size(delta: float, lam: float, edge: Edge, kmax: int, h: float):
    """Pick the contract size for a (+delta / -lam) day and return its DayOutcomes, or None.

    Rule (Theorem 2 + session constraint): with a non-negative edge use the
    smallest size whose bet resolves within the session with probability
    >= RESOLVE_PROB_MIN (if none does, the size with the highest resolution
    probability); with a negative edge use the largest size.  The target and
    stop must be at least one trade each at the chosen size."""
    cands = []
    for k in range(1, kmax + 1):
        up = k * (edge.reward - edge.cost_rt)
        down = k * (edge.loss + edge.cost_rt)
        if up <= 0 or delta < up - 1e-9 or lam < down - 1e-9:
            continue
        cands.append(k)
    if not cands:
        return None
    if edge.gamma < 0:
        return day_outcomes(delta, lam, max(cands), edge, h)
    best = None
    for k in cands:
        o = day_outcomes(delta, lam, k, edge, h)
        if 1.0 - o.p_unresolved >= RESOLVE_PROB_MIN:
            return o
        if best is None or o.p_unresolved < best.p_unresolved:
            best = o
    return best
